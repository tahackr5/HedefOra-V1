async function createFixtureRepository(source = canonicalSource) {
  const root = await mkdtemp(path.join(os.tmpdir(), "hedefora-openapi-gen-"));
  const contractPath = fixturePath(root, canonicalContractRelativePath);
  await mkdir(path.dirname(contractPath), { recursive: true });
  await writeFile(contractPath, source);
  return root;
}

async function copyGenerator(root) {
  const destination = path.join(root, "scripts", "generate-openapi.mjs");
  await mkdir(path.dirname(destination), { recursive: true });
  await copyFile(generatorPath, destination);
}

function runGenerator(root, mode, environment = {}) {
  return spawnSync(
    process.execPath,
    [path.join(root, "scripts", "generate-openapi.mjs"), mode],
    {
      cwd: path.dirname(root),
      encoding: "utf8",
      env: childEnvironment(environment),
      timeout: 10_000,
      windowsHide: true,
    },
  );
}

function childEnvironment(overrides) {
  const environment = { ...overrides };
  for (const name of ["ComSpec", "PATHEXT", "SystemRoot", "TEMP", "TMP"]) {
    if (process.env[name] !== undefined) environment[name] = process.env[name];
  }
  return environment;
}

function fixturePath(root, relativePath) {
  return path.join(root, ...relativePath.split("/"));
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}
