test("runtime inventory rejects incomplete and nonregular Git index entries", async () => {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "hedefora-runtime-invalid-index-"),
  );
  try {
    await seedExactRuntimeInventory(root);

    const intentToAddSource = "internal/platform/http/handler.go";
    runGit(root, "rm", "--cached", "--quiet", intentToAddSource);
    runGit(root, "add", "--intent-to-add", intentToAddSource);
    assert.deepEqual(await findGeneratedArtifacts(root), [
      `${intentToAddSource}#invalid-runtime-index-entry`,
    ]);
    runGit(root, "add", intentToAddSource);

    const symlinkModeSource = "internal/platform/http/server.go";
    const objectId = runGitOutput(root, "hash-object", "-w", symlinkModeSource);
    runGit(
      root,
      "update-index",
      "--add",
      "--cacheinfo",
      "120000",
      objectId,
      symlinkModeSource,
    );
    assert.deepEqual(await findGeneratedArtifacts(root), [
      `${symlinkModeSource}#invalid-runtime-index-entry`,
    ]);
    runGit(
      root,
      "update-index",
      "--cacheinfo",
      "100644",
      objectId,
      symlinkModeSource,
    );

    const hiddenIntentSource = "internal/platform/health/service.go";
    await writeFile(path.join(root, ...hiddenIntentSource.split("/")), "");
    runGit(root, "rm", "--cached", "--quiet", "--force", hiddenIntentSource);
    runGit(root, "add", "--intent-to-add", hiddenIntentSource);
    runGit(root, "update-index", "--skip-worktree", hiddenIntentSource);
    assert.deepEqual(await findGeneratedArtifacts(root), [
      `${hiddenIntentSource}#invalid-runtime-index-entry`,
    ]);

    runGit(root, "update-index", "--no-skip-worktree", hiddenIntentSource);
    runGit(root, "add", hiddenIntentSource);
    assert.deepEqual(await findGeneratedArtifacts(root), []);
    runGit(root, "rm", "--cached", "--quiet", "--force", hiddenIntentSource);
    runGit(root, "add", "--intent-to-add", hiddenIntentSource);
    runGit(root, "update-index", "--assume-unchanged", hiddenIntentSource);
    assert.deepEqual(await findGeneratedArtifacts(root), [
      `${hiddenIntentSource}#invalid-runtime-index-entry`,
    ]);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

