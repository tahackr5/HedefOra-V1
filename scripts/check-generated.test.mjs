function runGit(root, ...arguments_) {
  const result = spawnSync("git", ["-C", root, ...arguments_], {
    encoding: "utf8",
  });
  assert.equal(
    result.status,
    0,
    `git ${arguments_.join(" ")} failed: ${result.stderr || result.error?.message}`,
  );
}

function runGitOutput(root, ...arguments_) {
  const result = spawnSync("git", ["-C", root, ...arguments_], {
    encoding: "utf8",
  });
  assert.equal(
    result.status,
    0,
    `git ${arguments_.join(" ")} failed: ${result.stderr || result.error?.message}`,
  );
  return result.stdout.trim();
}

function exactRuntimeInventory() {
  return [
    ...allowedW001DatabaseFiles,
    ...allowedW001GeneratedSourceFiles,
    ...allowedW001InfrastructureFiles,
    ...allowedW001PostgresTestSourceFiles,
    ...allowedW001RuntimeSourceFiles,
  ].sort();
}

async function seedExactRuntimeInventory(root, { track = true } = {}) {
  const sources = exactRuntimeInventory();
  for (const source of sources) {
    await writeRuntimeFixtureFile(root, source);
  }
  if (track) {
    runGit(root, "init", "--quiet");
    runGit(root, "add", ...sources);
  }
}

async function writeRuntimeFixtureFile(root, source) {
  const destination = path.join(root, ...source.split("/"));
  await mkdir(path.dirname(destination), { recursive: true });
  const packageName = source.startsWith("cmd/") ? "main" : "fixture";
  await writeFile(destination, `package ${packageName}\n`);
}
