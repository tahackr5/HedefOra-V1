test("generated artifacts and W001 runtime roots fail closed", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "hedefora-generated-"));
  try {
    await mkdir(path.join(root, "internal", "generated", "openapi"), {
      recursive: true,
    });
    await mkdir(path.join(root, "internal", "platform", "app"), {
      recursive: true,
    });
    await mkdir(path.join(root, "apps", "web", "src", "generated"), {
      recursive: true,
    });
    await writeFile(
      path.join(root, "apps", "web", "src", "generated", "placeholder.txt"),
      "fixture\n",
    );
    await mkdir(path.join(root, "api"));
    await mkdir(path.join(root, "misc"));
    await mkdir(path.join(root, "scripts"));
    await mkdir(path.join(root, "tools", "repolint"), { recursive: true });
    await writeFile(
      path.join(root, "apps", "web", "index.html"),
      "<script>window.productBehavior = true;</script>\n",
    );
    await writeFile(
      path.join(root, "apps", "web", "src", "App.tsx"),
      "export function App() { return null; }\n",
    );
    await writeFile(
      path.join(root, "apps", "web", "src", "Feature.tsx"),
      "export function Feature() { return null; }\n",
    );
    await writeFile(path.join(root, "api", "server.go"), "package api\n");
    await writeFile(path.join(root, "api", "client.generated"), "{}\n");
    await writeFile(path.join(root, "api", "client.generated.json"), "{}\n");
    await writeFile(
      path.join(root, "scripts", "check-policy.mjs"),
      "export {};\n",
    );
    await writeFile(
      path.join(root, "tools", "repolint", "new.go"),
      "package repolint\n",
    );
    const symlinkFindings = [];
    for (const fixture of [
      {
        destination: path.join(root, "apps", "web", "src", "LinkedFeature.tsx"),
        finding: "apps/web/src/LinkedFeature.tsx#symbolic-link",
        source: path.join(root, "apps", "web", "src", "App.tsx"),
        type: undefined,
      },
      {
        destination: path.join(root, "apps", "web", "src", "linked-src"),
        finding: "apps/web/src/linked-src#symbolic-link",
        source: path.join(root, "apps", "web", "src"),
        type: "dir",
      },
    ]) {
      try {
        await symlink(fixture.source, fixture.destination, fixture.type);
        symlinkFindings.push(fixture.finding);
      } catch (error) {
        if (!new Set(["EACCES", "EPERM"]).has(error?.code)) throw error;
      }
    }
    await writeFile(
      path.join(root, "misc", "client.generated.ts"),
      "export {};\n",
    );
    await writeFile(
      path.join(root, "misc", "marker.go"),
      "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n",
    );
    await writeFile(
      path.join(root, "internal", "generated", "openapi", "openapi.gen.go"),
      "// Code generated by HedefOra sealed OpenAPI renderer. DO NOT EDIT.\npackage openapi\n",
    );
    await writeFile(
      path.join(root, "internal", "generated", "openapi", "extra.gen.go"),
      "package openapi\n",
    );
    await writeFile(
      path.join(root, "internal", "platform", "app", "app.go"),
      "package app\n",
    );

    const expectedFindings = [
      "api/client.generated",
      "api/client.generated.json",
      "api/server.go#unexpected-source",
      "apps/web/index.html#inline-behavior",
      "apps/web/src/Feature.tsx#unexpected-source",
      "apps/web/src/generated",
      "internal/generated/openapi/extra.gen.go#unexpected-runtime-source",
      "internal/platform/app/app.go#unexpected-runtime-source",
      "misc/client.generated.ts",
      "misc/marker.go#generated-marker",
      ...symlinkFindings,
    ].sort();
    assert.deepEqual(await findGeneratedArtifacts(root), expectedFindings);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("only the two exact W001 supply-chain Go tool files are allowed", async () => {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "hedefora-w001-tool-source-"),
  );
  try {
    const toolRoot = path.join(
      root,
      "tools",
      "osvdbcheck",
      "cmd",
      "osvdbcheck",
    );
    await mkdir(toolRoot, { recursive: true });
    await mkdir(path.join(root, "tools", "osvdbcheck", "cmd", "other"), {
      recursive: true,
    });
    await writeFile(path.join(toolRoot, "main.go"), "package main\n");
    await writeFile(path.join(toolRoot, "main_test.go"), "package main\n");
    await writeFile(path.join(toolRoot, "helper.go"), "package main\n");
    await writeFile(
      path.join(root, "tools", "osvdbcheck", "cmd", "other", "main.go"),
      "package main\n",
    );

    assert.deepEqual(await findGeneratedArtifacts(root), [
      "tools/osvdbcheck/cmd/osvdbcheck/helper.go#unexpected-source",
      "tools/osvdbcheck/cmd/other/main.go#unexpected-source",
    ]);
    assert.equal(
      isAllowedPreRuntimeSource("tools/osvdbcheck/cmd/osvdbcheck/main.go"),
      true,
    );
    assert.equal(
      isAllowedPreRuntimeSource("tools/osvdbcheck/cmd/osvdbcheck/Main.go"),
      false,
    );

    await writeFile(
      path.join(toolRoot, "main.go"),
      "// Code generated by fixture. DO NOT EDIT.\npackage main\n",
    );
    assert.deepEqual(await findGeneratedArtifacts(root), [
      "tools/osvdbcheck/cmd/osvdbcheck/helper.go#unexpected-source",
      "tools/osvdbcheck/cmd/osvdbcheck/main.go#generated-marker",
      "tools/osvdbcheck/cmd/other/main.go#unexpected-source",
    ]);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

