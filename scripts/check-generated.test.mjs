import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { findGeneratedArtifacts } from "./check-generated.mjs";

test("generated artifacts and W001 runtime roots fail closed", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "hedefora-generated-"));
  try {
    await mkdir(path.join(root, "internal"));
    await mkdir(path.join(root, "apps", "web", "src", "generated"), {
      recursive: true,
    });
    await mkdir(path.join(root, "misc"));
    await writeFile(
      path.join(root, "misc", "client.generated.ts"),
      "export {};\n",
    );
    await writeFile(
      path.join(root, "misc", "marker.go"),
      "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n",
    );

    assert.deepEqual(await findGeneratedArtifacts(root), [
      "apps/web/src/generated",
      "internal",
      "misc/client.generated.ts",
      "misc/marker.go#generated-marker",
    ]);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
