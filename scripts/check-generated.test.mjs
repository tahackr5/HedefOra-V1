test("the cmd runtime root rejects every non-allowlisted file independent of extension", async () => {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "hedefora-runtime-command-boundary-"),
  );
  try {
    const commandRoot = path.join(root, "cmd", "hedefora");
    await mkdir(commandRoot, { recursive: true });
    await writeFile(path.join(commandRoot, "main.go"), "package main\n");
    await writeFile(path.join(commandRoot, "main_test.go"), "package main\n");

    const rejectedFiles = [
      "assembly-lower.s",
      "assembly-upper.S",
      "extensionless",
      "object.syso",
      "payload.bin",
    ];
    for (const filename of rejectedFiles) {
      await writeFile(path.join(commandRoot, filename), "fixture\n");
    }

    assert.deepEqual(
      await findGeneratedArtifacts(root),
      rejectedFiles
        .map((filename) => `cmd/hedefora/${filename}#unexpected-runtime-source`)
        .sort(),
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("ignored cmd files cannot bypass the exact runtime source boundary", async () => {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "hedefora-ignored-runtime-command-"),
  );
  try {
    runGit(root, "init", "--quiet");
    const commandRoot = path.join(root, "cmd", "hedefora");
    await mkdir(commandRoot, { recursive: true });
    await writeFile(path.join(root, ".gitignore"), "cmd/hedefora/ignored-*\n");
    await writeFile(
      path.join(commandRoot, "main.go"),
      'package main\n\nimport _ "embed"\n\n//go:embed ignored-embedded.bin\nvar embedded []byte\n\nfunc main() {}\n',
    );
    await writeFile(path.join(commandRoot, "main_test.go"), "package main\n");

    const ignoredFiles = [
      "ignored-assembly.s",
      "ignored-embedded.bin",
      "ignored-extensionless",
      "ignored-object.syso",
    ];
    for (const filename of ignoredFiles) {
      await writeFile(path.join(commandRoot, filename), "fixture\n");
    }
    const symlinkFindings = [];
    try {
      await symlink(
        path.join(commandRoot, "main.go"),
        path.join(commandRoot, "ignored-link.s"),
      );
      symlinkFindings.push("cmd/hedefora/ignored-link.s#symbolic-link");
    } catch (error) {
      if (!new Set(["EACCES", "EPERM"]).has(error?.code)) throw error;
    }
    runGit(
      root,
      "add",
      ".gitignore",
      "cmd/hedefora/main.go",
      "cmd/hedefora/main_test.go",
    );

    assert.deepEqual(
      await findGeneratedArtifacts(root),
      [
        ...ignoredFiles.map(
          (filename) => `cmd/hedefora/${filename}#unexpected-runtime-source`,
        ),
        ...symlinkFindings,
      ].sort(),
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("force-tracked source in ignored output directories fails closed", async () => {
  const root = await mkdtemp(
    path.join(os.tmpdir(), "hedefora-tracked-output-"),
  );
  try {
    runGit(root, "init", "--quiet");
    const outputDirectories = [
      ".cache",
      ".pnpm-store",
      "artifacts",
      "build",
      "coverage",
      "dist",
      "node_modules",
    ];
    await writeFile(
      path.join(root, ".gitignore"),
      `${outputDirectories.map((directory) => `${directory}/`).join("\n")}\n`,
    );
    runGit(root, "add", ".gitignore");
    for (const directory of outputDirectories) {
      await mkdir(path.join(root, directory), { recursive: true });
      await writeFile(
        path.join(root, directory, "feature.js"),
        "export const feature = true;\n",
      );
      runGit(root, "add", "--force", `${directory}/feature.js`);
    }
    await writeFile(
      path.join(root, "dist", "ignored-untracked.js"),
      "export const ignored = true;\n",
    );
    await mkdir(path.join(root, "misc"));
    await writeFile(
      path.join(root, "misc", "Feature.TSX"),
      "export function Feature() { return null; }\n",
    );
    await writeFile(
      path.join(root, "misc", "marker.GO"),
      "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n",
    );
    await writeFile(
      path.join(root, "misc", "index.HTML"),
      '<button onclick="window.run()">Run</button>\n',
    );
    runGit(
      root,
      "add",
      "misc/Feature.TSX",
      "misc/marker.GO",
      "misc/index.HTML",
    );

    assert.deepEqual(await findGeneratedArtifacts(root), [
      ".cache/feature.js#unexpected-source",
      ".pnpm-store/feature.js#unexpected-source",
      "artifacts/feature.js#unexpected-source",
      "build/feature.js#unexpected-source",
      "coverage/feature.js#unexpected-source",
      "dist/feature.js#unexpected-source",
      "misc/Feature.TSX#unexpected-source",
      "misc/index.HTML#inline-behavior",
      "misc/marker.GO#generated-marker",
      "node_modules/feature.js#unexpected-source",
    ]);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

function runGit(root, ...arguments_) {
  const result = spawnSync("git", ["-C", root, ...arguments_], {
    encoding: "utf8",
  });
  assert.equal(
    result.status,
    0,
    `git ${arguments_.join(" ")} failed: ${result.stderr || result.error?.message}`,
  );
}
